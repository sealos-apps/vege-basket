function sanitizeExportFileName(value: string) {
  const cleaned = Array.from(String(value ?? ''), (char) => {
    if ('<>:"/\\|?*'.includes(char)) return '-'
    const code = char.charCodeAt(0)
    return code >= 0 && code <= 31 ? '-' : char
  }).join('')
  return cleaned
    .trim()
    .replace(/\s+/g, '-')
    .replace(/-+/g, '-')
    .replace(/^-|-$/g, '') || 'record'
}

