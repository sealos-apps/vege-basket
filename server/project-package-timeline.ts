export async function exportProjectPackageTimeline(projectId: number, eventId?: number) {
  const projectResult = await query<{
    owner_display_name: string
    owner_email: string
    project_name: string
  }>(
    `
    select p.name as project_name,
           owner.email as owner_email,
           owner.display_name as owner_display_name
    from projects p
    join users owner on owner.id = p.user_id
    where p.id = $1
    `,
    [projectId],
  )
  const project = projectResult.rows[0]
  if (!project) throw new Error('Project not found')

  const timeline = await getProjectPackageTimeline(projectId)
  const relatedTodoDetailsResult = await query<OperationRelatedTodoExportRow>(
    `
    select t.project_package_operation_id as operation_id,
           t.todo_id,
           todo.title as todo_title,
           t.note,
           operation_author.display_name as operation_note_author_display_name,
           operation_author.email as operation_note_author_email,
           author.display_name as note_author_display_name,
           author.email as note_author_email
    from project_package_operation_todos t
    join project_package_operations o on o.id = t.project_package_operation_id
    join project_package_events e on e.id = o.project_package_event_id
    join todos todo on todo.id = t.todo_id
    left join users operation_author on operation_author.id = t.note_author_user_id
    left join todo_notes note on note.todo_id = t.todo_id
      and note.source_operation_id = o.id
    left join users author on author.id = note.author_user_id
    where e.project_id = $1
    order by t.created_at asc, t.todo_id asc
    `,
    [projectId],
  )
  const relatedTodoDetailsByOperation = new Map<number, OperationRelatedTodoExportDetail[]>()
  for (const row of relatedTodoDetailsResult.rows) {
    const operationId = Number(row.operation_id)
    const details = relatedTodoDetailsByOperation.get(operationId) ?? []
    details.push({
      todoId: Number(row.todo_id),
      title: decryptText(row.todo_title),
      note: row.note ? decryptText(row.note) : '',
      noteAuthorName:
        row.operation_note_author_display_name ??
        row.operation_note_author_email ??
        row.note_author_display_name ??
        row.note_author_email ??
        '',
    })
    relatedTodoDetailsByOperation.set(operationId, details)
  }
  const projectName = decryptText(project.project_name)
  const ownerName = project.owner_display_name || project.owner_email.split('@')[0] || project.owner_email
  const selectedEvent = eventId == null
    ? null
    : timeline.events.find((event) => event.id === eventId) ?? null
  if (eventId != null && !selectedEvent) throw new Error('Event not found')
  const sourceRevisions = new Set(
    (selectedEvent ? [selectedEvent] : timeline.events)
      .flatMap((event) => event.groups)
      .flatMap((group) => group.items)
      .flatMap((item) => item.sourceConfigRevision ? [item.sourceConfigRevision] : []),
  )
  const rulesByRevision = new Map<number, readonly PackageMarketRule[]>()
  await Promise.all([...sourceRevisions].map(async (revision) => {
    const rules = await getPackageMarketRulesForConfigRevision(revision)
    if (rules) rulesByRevision.set(revision, rules)
  }))
  const markdown = selectedEvent
    ? [
      `# ${textValue(projectName, '未命名项目')} · ${textValue(selectedEvent.title, '未命名事件')} 时间线`,
      ...buildProjectPackageEventMarkdown(selectedEvent, relatedTodoDetailsByOperation, rulesByRevision),
      '',
    ].join('\n')
    : buildProjectPackageTimelineMarkdown(
      projectName,
      ownerName,
      timeline,
      relatedTodoDetailsByOperation,
      rulesByRevision,
    )
  const timestamp = formatExportDateTimeForFileName(new Date())
  const fileName = sanitizeExportFileName(
    `${projectName}-${selectedEvent ? selectedEvent.title : '项目'}时间线-${timestamp}.md`,
  )

  return { fileName, markdown }
}

