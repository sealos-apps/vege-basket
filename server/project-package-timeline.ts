function buildProjectCompletionGraph(rows: ProjectOperationTodoLinkRow[]) {
  const operationToTodos = new Map<number, number[]>()
  const todoToOperations = new Map<number, number[]>()

  for (const row of rows) {
    const operationId = Number(row.operation_id)
    if (!operationToTodos.has(operationId)) {
      operationToTodos.set(operationId, [])
    }
    if (!row.todo_id) continue
    const todoId = Number(row.todo_id)
    operationToTodos.set(operationId, [...(operationToTodos.get(operationId) ?? []), todoId])
    todoToOperations.set(todoId, [...(todoToOperations.get(todoId) ?? []), operationId])
  }

  return { operationToTodos, todoToOperations }
}

function collectConnectedProjectCompletionIds(
  graph: ReturnType<typeof buildProjectCompletionGraph>,
  seeds: {
    operationIds?: number[]
    todoIds?: number[]
  },
) {
  const operationIds = new Set(normalizePositiveIds(seeds.operationIds ?? []))
  const todoIds = new Set(normalizePositiveIds(seeds.todoIds ?? []))
  const operationQueue = [...operationIds]
  const todoQueue = [...todoIds]

  while (operationQueue.length > 0 || todoQueue.length > 0) {
    while (operationQueue.length > 0) {
      const operationId = operationQueue.shift()
      if (operationId == null) continue
      for (const todoId of graph.operationToTodos.get(operationId) ?? []) {
        if (todoIds.has(todoId)) continue
        todoIds.add(todoId)
        todoQueue.push(todoId)
      }
    }

    while (todoQueue.length > 0) {
      const todoId = todoQueue.shift()
      if (todoId == null) continue
      for (const operationId of graph.todoToOperations.get(todoId) ?? []) {
        if (operationIds.has(operationId)) continue
        operationIds.add(operationId)
        operationQueue.push(operationId)
      }
    }
  }

  return {
    operationIds: [...operationIds],
    todoIds: [...todoIds],
  }
}

