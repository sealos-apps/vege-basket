function textValue(value: unknown, fallback = '-') {
  const normalized = String(value ?? '').trim()
  return normalized || fallback
}

function packageDownloadUrlValue(
  item: Pick<ProjectPackageItem, 'channel' | 'objectKey' | 'sourceConfigRevision' | 'sourcePackageId'>,
  rulesByRevision?: ReadonlyMap<number, readonly PackageMarketRule[]>,
) {
  try {
    const channel = item.channel === 'ci' || item.channel === 'release' ? item.channel : null
    const rules = item.sourceConfigRevision
      ? rulesByRevision?.get(item.sourceConfigRevision)
      : undefined
    if (item.sourceConfigRevision && !rules) {
      return '临时下载链接生成失败：历史平台配置不可用'
    }
    if (!channel || !isPackageMarketObjectKeyAllowedForRule({
      channel,
      objectKey: item.objectKey,
      packageId: item.sourcePackageId,
      rules,
    })) {
      return '临时下载链接生成失败：安装包对象路径与安装包规则不匹配'
    }
    return createPackageItemDownloadUrl(item.objectKey)
  } catch (error) {
    return `临时下载链接生成失败：${String((error as Error).message ?? error)}`
  }
}

function packageFileName(objectKey: string, fallback: string) {
  const segments = String(objectKey ?? '')
    .split('/')
    .map((segment) => segment.trim())
    .filter(Boolean)
  return segments.at(-1) || textValue(fallback)
}

function escapeMarkdownLinkLabel(value: string) {
  return value.replace(/\\/g, '\\\\').replace(/\[/g, '\\[').replace(/\]/g, '\\]')
}

function normalizeExportNoteText(value: unknown, fallback = '未填写') {
  const normalized = String(value ?? '').trim()
  if (!normalized) return fallback
  return normalized
    .replace(/\r\n/g, '\n')
    .split('\n')
    .map((line) => line.trim())
    .filter(Boolean)
    .join(' / ')
}

function buildPackageTimelineNodes(group: ProjectPackageGroup) {
  const itemNodes = group.items.map((item) => ({
    type: 'package-operation' as const,
    createdAt: item.createdAt,
    item,
  }))
  const operationNodes = group.operations.map((operation) => ({
    type: operation.kind,
    createdAt: operation.createdAt,
    operation,
  }))
  return [...itemNodes, ...operationNodes].sort((left, right) =>
    left.createdAt.localeCompare(right.createdAt),
  )
}

function buildOperationMarkdown(
  operation: ProjectPackageOperation,
  relatedTodoDetails: OperationRelatedTodoExportDetail[] = [],
  level = '###',
  options: {
    headingNumber?: string
    listStyle?: boolean
    relatedTodoHeadingNumber?: string
  } = {},
) {
  const createdAt = formatExportDateTime(operation.createdAt)
  const relatedTodoLines = relatedTodoDetails.flatMap((detail, index) => {
    const lines = [
      `- 关联待办：${textValue(detail.title, `#${detail.todoId}`)}`,
      `  - 备注作者：${textValue(detail.noteAuthorName, '未填写')}`,
      `  - 备注内容：${normalizeExportNoteText(detail.note)}`,
    ]
    return index === 0 ? lines : ['', ...lines]
  })
  const relatedTodoBlock = relatedTodoLines.length > 0
    ? [
      '',
      `${level} ${options.relatedTodoHeadingNumber ? `${options.relatedTodoHeadingNumber} ` : ''}关联待办说明`,
      '',
      ...relatedTodoLines,
    ]
    : []
  if (operation.kind === 'document') {
    return [
      `${level} ${options.headingNumber ? `${options.headingNumber} ` : ''}文档：${textValue(operation.title, '未命名操作文档')}`,
      '',
      `- 时间：${createdAt}`,
      '',
      textValue(operation.content, '无内容'),
      ...relatedTodoBlock,
    ]
  }

  const eventLabel = textValue(operation.label, '操作事件')
  const operationTitle = textValue(operation.title, '')
  if (options.listStyle) {
    const lines = [`- ${createdAt} · ${eventLabel}`]
    if (operation.content) {
      if (operationTitle && operationTitle !== eventLabel) {
        lines.push('', `  - ${operationTitle}`)
      }
      lines.push('', textValue(operation.content, '无内容'))
    }
    if (relatedTodoLines.length > 0) {
      lines.push('', ...relatedTodoLines)
    }
    return lines
  }

  const detailLevel = `${level}#`
  const lines = [
    `${level} ${options.headingNumber ? `${options.headingNumber} ` : ''}${createdAt}`,
    '',
    `${detailLevel} ${eventLabel}`,
  ]
  if (operation.content) {
    if (operationTitle && operationTitle !== eventLabel) {
      lines.push('', `${detailLevel}# ${operationTitle}`, '', operation.content)
    } else {
      lines.push('', operation.content)
    }
  }
  lines.push(...relatedTodoBlock)
  return lines
}

function buildPackageTimelineMarkdown(
  group: ProjectPackageGroup,
  relatedTodoDetailsByOperation: Map<number, OperationRelatedTodoExportDetail[]>,
  rulesByRevision: ReadonlyMap<number, readonly PackageMarketRule[]>,
  options: {
    headingLevel?: string
    sectionNumber?: string
  } = {},
) {
  const headingLevel = options.headingLevel ?? '##'
  const lines: string[] = []
  const nodes = buildPackageTimelineNodes(group)
  const packageOperations = nodes.filter((node) => node.type !== 'package-operation')
  const packageRecords = nodes.filter((node) => node.type === 'package-operation')
  const headingPrefix = options.sectionNumber ? `${options.sectionNumber}. ` : ''
  const linkSectionPrefix = options.sectionNumber ? `${options.sectionNumber}.1 ` : ''

  if (packageRecords.length > 0) {
    const details = Array.from(
      new Set(
        packageRecords.map((node) => {
          if (node.type !== 'package-operation') return ''
          const item = node.item
          return [textValue(item.channelLabel), textValue(item.arch), textValue(item.version, '未知版本')]
            .filter(Boolean)
            .join(' · ')
        }).filter(Boolean),
      ),
    )
    lines.push(`${headingLevel} ${headingPrefix}${group.packageName} · ${details.join('；')}`, '')
    lines.push(`${headingLevel}# ${linkSectionPrefix}临时下载链接`, '')
    packageRecords.forEach((node) => {
      if (node.type !== 'package-operation') return
      const item = node.item
      const fileName = packageFileName(item.objectKey, item.packageName)
      const downloadUrl = packageDownloadUrlValue(item, rulesByRevision)
      if (downloadUrl.startsWith('临时下载链接生成失败：')) {
        lines.push(`- ${textValue(fileName)}：${downloadUrl}`)
        return
      }
      lines.push(`- [${escapeMarkdownLinkLabel(textValue(fileName))}](${downloadUrl})`)
    })
    lines.push('')
  } else {
    lines.push(`${headingLevel} ${headingPrefix}${group.packageName}`, '')
  }

  if (packageOperations.length === 0) {
    lines.push('暂无时间线记录。')
    return lines
  }

  packageOperations.forEach((node) => {
    lines.push(
      ...buildOperationMarkdown(
        node.operation,
        relatedTodoDetailsByOperation.get(node.operation.id) ?? [],
        `${headingLevel}#`,
        { listStyle: true },
      ),
      '',
    )
  })

  return lines
}

function countPackageItems(timeline: ProjectPackageTimeline) {
  return timeline.events.reduce(
    (total, event) =>
      total + event.groups.reduce((eventTotal, group) => eventTotal + group.items.length, 0),
    0,
  )
}

function buildProjectPackageTimelineMarkdown(
  projectName: string,
  ownerName: string,
  timeline: ProjectPackageTimeline,
  relatedTodoDetailsByOperation: Map<number, OperationRelatedTodoExportDetail[]>,
  rulesByRevision: ReadonlyMap<number, readonly PackageMarketRule[]>,
) {
  const lines = [
    `# ${textValue(projectName, '未命名项目')} 项目时间线`,
    '',
    `- 项目负责人：${textValue(ownerName, '未填写')}`,
    `- 安装包操作记录：${countPackageItems(timeline)} 条`,
    `- 导出时间：${formatExportDateTime(new Date())}`,
  ]

  if (timeline.events.length === 0) {
    lines.push('', '暂无项目事件。')
    return `${lines.join('\n')}\n`
  }

  timeline.events.forEach((event, eventIndex) => {
    if (eventIndex > 0) {
      lines.push('', '---', '')
    }
    lines.push(...buildProjectPackageEventMarkdown(event, relatedTodoDetailsByOperation, rulesByRevision))
  })

  return `${lines.join('\n')}\n`
}

function buildProjectPackageEventMarkdown(
  event: ProjectPackageEvent,
  relatedTodoDetailsByOperation: Map<number, OperationRelatedTodoExportDetail[]>,
  rulesByRevision: ReadonlyMap<number, readonly PackageMarketRule[]>,
) {
  const lines: string[] = [
    '',
    `## ${formatExportDateTime(event.createdAt)}`,
    '',
    `### ${textValue(event.title, '未命名事件')}`,
    '',
    `- 交付人：${textValue(event.assigneeName, '未指派')}`,
    `- 交付时间：${event.deliveryStartAt} ~ ${event.deliveryEndAt}`,
    '',
    '### 1. 操作文档',
    '',
  ]
  if (event.operations.length === 0) {
    lines.push('暂无操作文档。', '')
  } else {
    let operationHeadingIndex = 1
    event.operations.forEach((operation) => {
      const relatedTodoDetails = relatedTodoDetailsByOperation.get(operation.id) ?? []
      const headingNumber = `1.${operationHeadingIndex}`
      const relatedTodoHeadingNumber = relatedTodoDetails.length > 0
        ? `1.${operationHeadingIndex + 1}`
        : undefined
      lines.push(
        ...buildOperationMarkdown(
          operation,
          relatedTodoDetails,
          '####',
          {
            headingNumber,
            relatedTodoHeadingNumber,
          },
        ),
        '',
      )
      operationHeadingIndex += relatedTodoDetails.length > 0 ? 2 : 1
    })
  }

  if (event.groups.length === 0) {
    lines.push('暂无安装包。', '')
    return lines
  }

  event.groups
    .slice()
    .sort((left, right) => left.packageName.localeCompare(right.packageName, 'zh-CN'))
    .forEach((group, groupIndex) => {
      lines.push(
        ...buildPackageTimelineMarkdown(group, relatedTodoDetailsByOperation, rulesByRevision, {
          headingLevel: '###',
          sectionNumber: String(groupIndex + 2),
        }),
        '',
      )
    })
  return lines
}

